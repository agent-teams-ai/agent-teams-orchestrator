const generator = '// @generated by protoc-gen-es v2.16.0 with parameter "target=ts,import_extension=js"';
const directive = ['/* eslint', 'disable */'].join('-');
const sourceHeader = /^\/\/ @generated from file [A-Za-z0-9_./-]+\.proto \(package [A-Za-z0-9_.]+, syntax proto3\)$/u;

/** Remove exactly the pinned generator's standalone blanket preamble line. */
export function normalizeGeneratedPreamble(source: string): string {
  const lines = source.split('\n');
  if (lines[0] !== generator || !sourceHeader.test(lines[1] ?? '') || lines[2] !== directive || lines[3] !== '') {
    throw new Error('Unexpected pinned Protobuf generator preamble');
  }
  lines.splice(2, 1);
  return lines.join('\n');
}
