import assert from 'node:assert/strict';
import test from 'node:test';
import { normalizeGeneratedPreamble } from './normalize-generated.ts';

const first = '// @generated by protoc-gen-es v2.16.0 with parameter "target=ts,import_extension=js"';
const second = '// @generated from file agentteams/control/v1/control.proto (package agentteams.control.v1, syntax proto3)';
const directive = ['/* eslint', 'disable */'].join('-');
const body = '\n/** License and protocol documentation remain exact. */\nexport const value: string = "body";\n';

test('normalization removes only the exact pinned preamble line and preserves every other byte', () => {
  assert.equal(normalizeGeneratedPreamble(`${first}\n${second}\n${directive}\n${body}`), `${first}\n${second}\n${body}`);
  for (const variant of [
    `${first.replace('2.16.0', '2.16.1')}\n${second}\n${directive}\n${body}`,
    `${first}\nunknown source header\n${directive}\n${body}`,
    `${first}\n${second}\n ${directive}\n${body}`,
    `${first}\n${second}\n${directive.replace(' */', ' extra-rule */')}\n${body}`,
    `${first}\n${second}\n${body}`,
    `${first}\r\n${second}\r\n${directive}\r\n${body}`,
  ]) {
    assert.throws(() => normalizeGeneratedPreamble(variant), /Unexpected pinned Protobuf generator preamble/u);
  }
});
